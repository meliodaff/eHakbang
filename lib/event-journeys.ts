/** Journey for a selected life-event id (e.g., from `/journey?event=...`). */
export function getJourneyByEventId(eventId: string): Journey | undefined {
  return EVENT_JOURNEYS[eventId];
}

/** Look up an event journey by its full journey id. */
export function getEventJourneyById(journeyId: string): Journey | undefined {
  return Object.values(EVENT_JOURNEYS).find((j) => j.id === journeyId);
}
