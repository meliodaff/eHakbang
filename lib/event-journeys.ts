import type { Journey, JourneyStep } from "./types";

/**
 * Per-life-event seed journeys. Requirements are normally AI-generated and
 * cached in Supabase (see lib/server/journey-requirements.ts); this map is
 * the fallback used when the eGov AI Assistant/Supabase aren't configured or
 * a call fails, so local dev and offline use still work. Also used directly by
 * JourneyScreen when no server-prefetched journey is available (e.g. tests).
 * Users are always routed to the official page for exact amounts/requirements.
 */

type StepSeed = Omit<JourneyStep, "step_number">;

function build(
  eventId: string,
  emoji: string,
  lifeEvent: string,
  summary: string,
  seeds: StepSeed[],
): Journey {
  const steps: JourneyStep[] = seeds.map((seed, i) => ({
    ...seed,
    step_number: i + 1,
  }));
  return {
    id: `ehakbang:journey:event:${eventId}`,
    event_id: eventId,
    emoji,
    life_event: lifeEvent,
    summary,
    total_steps: steps.length,
    record_updates: steps.filter((s) => s.step_type === "record_update").length,
    benefit_claims: steps.filter((s) => s.step_type === "benefit_claim").length,
    steps,
    status: "active",
    language: "en",
    created_at: "2026-07-22T00:00:00.000Z",
    completed_at: null,
    completed_step_numbers: [],
    paid_step_numbers: [],
    field_answers: {},
  };
}

